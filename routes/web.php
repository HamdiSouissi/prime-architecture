<?php

use App\Http\Controllers\ActivityController;
use App\Http\Controllers\Auth\AuthenticatedSessionController;
use App\Http\Controllers\Auth\EmailVerificationNotificationController;
use App\Http\Controllers\Auth\EmailVerificationPromptController;
use App\Http\Controllers\Auth\NewPasswordController;
use App\Http\Controllers\Auth\PasswordResetLinkController;
use App\Http\Controllers\Auth\VerifyEmailController;
use App\Http\Controllers\ClientContactController;
use App\Http\Controllers\ClientController;
use App\Http\Controllers\DashboardController;
use App\Http\Controllers\DocumentCategoryController;
use App\Http\Controllers\DocumentCommentController;
use App\Http\Controllers\DocumentController;
use App\Http\Controllers\DocumentVersionController;
use App\Http\Controllers\DocumentZipController;
use App\Http\Controllers\InvitationController;
use App\Http\Controllers\LocaleController;
use App\Http\Controllers\ProfileController;
use App\Http\Controllers\ProjectActionsController;
use App\Http\Controllers\ProjectController;
use App\Http\Controllers\UserController;
use Illuminate\Support\Facades\Route;

Route::view('/', 'welcome')->name('home');
Route::post('/locale', [LocaleController::class, 'update'])->name('locale.update');
Route::middleware('guest')->group(function () {
    Route::get('/login', [AuthenticatedSessionController::class, 'create'])->name('login');
    Route::post('/login', [AuthenticatedSessionController::class, 'store']);
    Route::get('/forgot-password', [PasswordResetLinkController::class, 'create'])->name('password.request');
    Route::post('/forgot-password', [PasswordResetLinkController::class, 'store'])->middleware('throttle:6,1')->name('password.email');
    Route::get('/reset-password/{token}', [NewPasswordController::class, 'create'])->name('password.reset');
    Route::post('/reset-password', [NewPasswordController::class, 'store'])->middleware('throttle:6,1')->name('password.store');
    Route::get('/invitation/{token}', [InvitationController::class, 'show'])->middleware('signed')->name('invitation.show');
    Route::post('/invitation/{token}', [InvitationController::class, 'store'])->middleware(['signed', 'throttle:10,1'])->name('invitation.store');
});
Route::middleware('auth')->group(function () {
    Route::post('/logout', [AuthenticatedSessionController::class, 'destroy'])->name('logout');
    Route::get('/verify-email', EmailVerificationPromptController::class)->name('verification.notice');
    Route::get('/verify-email/{id}/{hash}', VerifyEmailController::class)->middleware(['signed', 'throttle:6,1'])->name('verification.verify');
    Route::post('/email/verification-notification', [EmailVerificationNotificationController::class, 'store'])->middleware('throttle:6,1')->name('verification.send');
    Route::middleware('verified')->group(function () {
        Route::get('/dashboard', DashboardController::class)->name('dashboard');
        Route::post('/clients/{client}/restore', [ClientController::class, 'restore'])->withTrashed()->name('clients.restore');
        Route::post('/clients/{client}/contacts/{contact}/restore', [ClientContactController::class, 'restore'])->withTrashed()->name('clients.contacts.restore');
        Route::post('/clients/{client}/contacts', [ClientContactController::class, 'store'])->name('clients.contacts.store');
        Route::put('/clients/{client}/contacts/{contact}', [ClientContactController::class, 'update'])->name('clients.contacts.update');
        Route::delete('/clients/{client}/contacts/{contact}', [ClientContactController::class, 'destroy'])->name('clients.contacts.destroy');
        Route::resource('clients', ClientController::class);
        Route::post('/projects/{project}/restore', [ProjectController::class, 'restore'])->withTrashed()->name('projects.restore');
        Route::post('/projects/{project}/status', [ProjectActionsController::class, 'status'])->name('projects.status');
        Route::post('/projects/{project}/lead', [ProjectActionsController::class, 'lead'])->name('projects.lead');
        Route::post('/projects/{project}/members', [ProjectActionsController::class, 'addMember'])->name('projects.members.store');
        Route::delete('/projects/{project}/members/{member}', [ProjectActionsController::class, 'removeMember'])->name('projects.members.destroy');
        Route::post('/projects/{project}/notes', [ProjectActionsController::class, 'addNote'])->name('projects.notes.store');
        Route::delete('/projects/{project}/notes/{note}', [ProjectActionsController::class, 'removeNote'])->name('projects.notes.destroy');
        Route::resource('projects', ProjectController::class);

        Route::get('/projects/{project}/documents', [DocumentController::class, 'index'])->name('documents.index');
        Route::get('/projects/{project}/documents/create', [DocumentController::class, 'create'])->name('documents.create');
        Route::post('/projects/{project}/documents', [DocumentController::class, 'store'])->name('documents.store');
        Route::post('/projects/{project}/documents/zip', DocumentZipController::class)->name('documents.zip');
        Route::post('/projects/{project}/documents/{document}/restore', [DocumentController::class, 'restore'])->withTrashed()->name('documents.restore');
        Route::get('/projects/{project}/documents/{document}', [DocumentController::class, 'show'])->name('documents.show');
        Route::get('/projects/{project}/documents/{document}/edit', [DocumentController::class, 'edit'])->name('documents.edit');
        Route::put('/projects/{project}/documents/{document}', [DocumentController::class, 'update'])->name('documents.update');
        Route::delete('/projects/{project}/documents/{document}', [DocumentController::class, 'destroy'])->name('documents.destroy');
        Route::post('/projects/{project}/documents/{document}/versions', [DocumentVersionController::class, 'store'])->name('documents.versions.store');
        Route::get('/projects/{project}/documents/{document}/versions/{version}/download', [DocumentVersionController::class, 'download'])->name('documents.versions.download');
        Route::get('/projects/{project}/documents/{document}/versions/{version}/preview', [DocumentVersionController::class, 'preview'])->name('documents.versions.preview');
        Route::post('/projects/{project}/documents/{document}/versions/{version}/copy', [DocumentVersionController::class, 'copy'])->name('documents.versions.copy');
        Route::delete('/projects/{project}/documents/{document}/versions/{version}', [DocumentVersionController::class, 'destroy'])->name('documents.versions.destroy');
        Route::post('/projects/{project}/documents/{document}/versions/{version}/restore', [DocumentVersionController::class, 'restore'])->withTrashed()->name('documents.versions.restore');
        Route::post('/projects/{project}/documents/{document}/comments', [DocumentCommentController::class, 'store'])->name('documents.comments.store');
        Route::delete('/projects/{project}/documents/{document}/comments/{comment}', [DocumentCommentController::class, 'destroy'])->name('documents.comments.destroy');
        Route::get('/document-categories', [DocumentCategoryController::class, 'index'])->name('document-categories.index');
        Route::post('/document-categories', [DocumentCategoryController::class, 'store'])->name('document-categories.store');
        Route::put('/document-categories/{category}', [DocumentCategoryController::class, 'update'])->name('document-categories.update');
        Route::delete('/document-categories/{category}', [DocumentCategoryController::class, 'destroy'])->name('document-categories.destroy');

        Route::get('/profile', [ProfileController::class, 'edit'])->name('profile.edit');
        Route::patch('/profile', [ProfileController::class, 'update'])->name('profile.update');
        Route::put('/profile/password', [ProfileController::class, 'password'])->name('profile.password');
        Route::delete('/profile/sessions', [ProfileController::class, 'logoutOthers'])->name('profile.sessions.destroy');
        Route::post('/users/{user}/invitation', [UserController::class, 'resendInvitation'])->middleware(['permission:users.manage', 'throttle:6,1'])->name('users.invitation');
        Route::resource('users', UserController::class)->except(['show'])->middleware('permission:users.manage');
        Route::get('/activity', [ActivityController::class, 'index'])->middleware('permission:activity.view')->name('activity.index');
    });
});
Route::fallback(fn () => abort(404));
